SELECT S.SID, S.SNAME, COALESCE(SUM(C.COST), 0) AS TOTAL_VALUE
FROM SUPPLIERS S
LEFT JOIN CATALOG C ON S.SID = C.SID
GROUP BY S.SID, S.SNAME;

