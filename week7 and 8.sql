SELECT DISTINCT P.PNAME
FROM PARTS P
JOIN CATALOG C ON P.PID = C.PID;

SELECT S.SNAME
FROM SUPPLIERS S
JOIN CATALOG C ON S.SID = C.SID
GROUP BY S.SID, S.SNAME
HAVING COUNT(DISTINCT C.PID) >= ALL (
    SELECT COUNT(*)
    FROM PARTS
);

SELECT S.SNAME
FROM SUPPLIERS S
WHERE NOT EXISTS (
    SELECT P.PID
    FROM PARTS P
    WHERE P.COLOR = 'Red'
      AND NOT EXISTS (
          SELECT C.PID
          FROM CATALOG C
          WHERE C.SID = S.SID AND C.PID = P.PID
      )
);

